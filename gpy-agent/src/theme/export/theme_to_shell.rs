/// Emit the provenance header. `theme_name` is raw: it sits in a `#` comment, never expanded.
fn append_header(output: &mut String, shell: Shell, theme_name: &str) {
    push_line(output, format_args!("# GPY Theme: {theme_name}"));
    push_line(
        output,
        format_args!(
            "# Generated by gpy-agent for {}",
            match shell {
                Shell::Fish => "Fish",
                Shell::Zsh => "Zsh",
                Shell::Bash => "Bash",
            }
        ),
    );
    output.push('\n');
}

/// The enabled-segment list: [`Config::effective_segments`].
fn append_enabled_segments(output: &mut String, shell: Shell, config: &Config) {
    let segments = config.effective_segments().collect::<Vec<_>>().join(" ");

    // Bash needs a space-separated string: `$arr` expands to the first element only.
    match shell {
        Shell::Fish => push_line(output, format_args!("set -g __enabled_segments {segments}")),
        Shell::Zsh => push_line(
            output,
            format_args!("typeset -g -a __enabled_segments=({segments})"),
        ),
        Shell::Bash => push_line(output, format_args!("__enabled_segments=\"{segments}\"")),
    }
}

/// Sorted language marker file names from `marker_file_names()`, for shell pre-filters.
/// Shell-safe; arrays are never exported (Bash can't export arrays).
fn append_lang_marker_files(output: &mut String, shell: Shell) {
    let mut names: Vec<&str> = crate::language::metadata::marker_file_names()
        .iter()
        .copied()
        .collect();
    names.sort_unstable();
    let joined = names.join(" ");

    match shell {
        Shell::Fish => push_line(
            output,
            format_args!("set -g __gpy_lang_marker_files {joined}"),
        ),
        Shell::Zsh => push_line(
            output,
            format_args!("typeset -g -a __gpy_lang_marker_files=({joined})"),
        ),
        Shell::Bash => push_line(output, format_args!("__gpy_lang_marker_files=({joined})")),
    }
}

/// Chevron-relevant segments and their `__color_*_bg` var, in Bash/Zsh case-arm order.
/// `git` and `status` are handled separately: the git bg is the state colour the
/// agent cached, and the status bg depends on the previous exit status.
pub(crate) const SEGMENT_BG_VARS: &[(&str, &str)] = &[
    ("language", "__color_language_bg"),
    ("directory", "__color_directory_bg"),
    ("duration", "__color_duration_bg"),
    ("clock", "__color_clock_bg"),
];

/// Emit `__gpy_segment_bg` for Bash/Zsh (no-op for Fish).
///
/// `__gpy_segment_bg SEG` prints to stdout; `__gpy_segment_bg SEG VAR` uses
/// `printf -v` to avoid a subshell fork on the hot path.
/// `status` picks ok/fail bg by `__gpy_last_status`.
fn append_segment_bg_function(output: &mut String, shell: Shell) {
    if matches!(shell, Shell::Fish) {
        return;
    }

    output.push('\n');
    push_line(output, format_args!("__gpy_segment_bg() {{"));
    push_line(output, format_args!("    local __gpy_sbg=\"\""));
    push_line(output, format_args!("    case \"$1\" in"));
    let helper_defined = match shell {
        Shell::Zsh => "(( ${+functions[__gpy_git_segment_bg]} ))",
        Shell::Bash | Shell::Fish => "declare -F __gpy_git_segment_bg >/dev/null",
    };
    push_line(
        output,
        format_args!(
            "        git) if {helper_defined}; then __gpy_git_segment_bg __gpy_sbg; else __gpy_sbg=\"${{__color_git_clean_bg:-}}\"; fi ;;"
        ),
    );
    for (segment, var) in SEGMENT_BG_VARS {
        push_line(
            output,
            format_args!("        {segment}) __gpy_sbg=\"${{{var}:-}}\" ;;"),
        );
    }
    push_line(output, format_args!("        status)"));
    push_line(
        output,
        format_args!("            if [[ \"${{__gpy_last_status:-0}}\" -eq 0 ]]; then"),
    );
    push_line(
        output,
        format_args!("                __gpy_sbg=\"${{__color_status_ok_bg:-green}}\""),
    );
    push_line(output, format_args!("            else"));
    push_line(
        output,
        format_args!("                __gpy_sbg=\"${{__color_status_fail_bg:-red}}\""),
    );
    push_line(output, format_args!("            fi"));
    push_line(output, format_args!("            ;;"));
    push_line(output, format_args!("        *) __gpy_sbg=\"\" ;;"));
    push_line(output, format_args!("    esac"));
    push_line(output, format_args!("    if [[ -n \"$2\" ]]; then"));
    push_line(
        output,
        format_args!("        printf -v \"$2\" '%s' \"$__gpy_sbg\""),
    );
    push_line(output, format_args!("    else"));
    push_line(output, format_args!("        printf '%s' \"$__gpy_sbg\""));
    push_line(output, format_args!("    fi"));
    push_line(output, format_args!("}}"));
}

/// The plugin data an export writes besides the theme: gathered from plugin
/// discovery by the caller, so [`theme_to_shell`] stays a pure function.
#[derive(Debug, Clone, Default)]
pub(crate) struct PluginExports {
    /// `.fish` segment files of `file` plugins by segment name (Fish only).
    pub segment_files: BTreeMap<String, String>,
    /// Enabled script segments, written for every shell.
    pub scripts: ScriptSegmentExports,
}

/// The built-in assignments: global settings, prompt, built-in segments, status,
/// git/language colours and delimiters. Everything [`theme_to_shell`] writes
/// before the plugin segments, shared with [`builtin_export_names`].
fn append_builtin_assignments(
    output: &mut String,
    theme: &ThemeConfig,
    theme_name: &str,
    config: &Config,
    colors: ShellColors<'_>,
    glyphs: Glyphs,
) {
    append_global_assignments(output, colors.shell, theme, theme_name, config);
    append_prompt_assignments(output, colors, theme);
    append_builtin_segment_assignments(output, colors, theme);
    append_status_assignments(output, colors, theme, glyphs);
    append_git_language_color_assignments(output, colors, theme);
    append_delimiter_assignments(output, colors, theme, glyphs);
}

/// Every variable name the built-in assignments write, derived by running
/// [`append_builtin_assignments`] itself so the set cannot drift from the emitter.
/// Each built-in assignment is unconditional (values vary, names do not), so a
/// default theme and config name them all. Plugin segment themes must not export
/// any of these.
pub(crate) fn builtin_export_names() -> &'static HashSet<String> {
    static NAMES: LazyLock<HashSet<String>> = LazyLock::new(|| {
        let palette = Palette::default();
        let colors = ShellColors {
            shell: Shell::Bash,
            palette: &palette,
        };
        let mut output = String::new();
        append_builtin_assignments(
            &mut output,
            &ThemeConfig::default(),
            "",
            &Config::default(),
            colors,
            Glyphs::Nerd,
        );
        output
            .lines()
            .filter_map(assigned_name)
            .map(str::to_owned)
            .collect()
    });
    &NAMES
}

/// The variable a Bash export line (`NAME=…`, `export NAME=…`, `unset NAME`) assigns.
pub(super) fn assigned_name(line: &str) -> Option<&str> {
    let statement = line
        .strip_prefix("export ")
        .or_else(|| line.strip_prefix("unset "))
        .unwrap_or(line);
    let name = statement
        .split_once('=')
        .map_or(statement, |(name, _)| name);
    (!name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'))
        .then_some(name)
}

/// Serialize a theme into shell assignments. Call order is the export contract,
/// pinned by snapshots. Every assigned value is escaped once, in
/// [`ShellAssignment::render`](super::shell_assignment::ShellAssignment::render) or
/// [`append_shell_list`](super::shell_assignment::append_shell_list), by
/// [`escape_shell_value`](super::shell_assignment::escape_shell_value); colors are validated
/// upstream and resolved against `palette` (see [`ShellColors`]).
pub(crate) fn theme_to_shell(
    theme: &ThemeConfig,
    theme_name: &str,
    config: &Config,
    shell: Shell,
    palette: &Palette,
    plugins: &PluginExports,
) -> String {
    let mut output = String::new();
    let colors = ShellColors { shell, palette };
    let glyphs = Glyphs::from(&config.ui);

    append_shell_assignment(
        &mut output,
        shell,
        ShellAssignment::local("__gpy_export_version", "1"),
    );
    append_header(&mut output, shell, theme_name);
    append_builtin_assignments(&mut output, theme, theme_name, config, colors, glyphs);

    append_plugin_segment_assignments(&mut output, colors, glyphs, &theme.segments.plugin);

    append_plugin_segment_file_assignments(&mut output, shell, &plugins.segment_files);
    append_script_segment_assignments(&mut output, shell, &plugins.scripts);
    append_enabled_segments(&mut output, shell, config);
    append_lang_marker_files(&mut output, shell);
    append_segment_bg_function(&mut output, shell);

    output
}
