//! [`theme_to_shell`]: the export entry point, its header, segment list and Bash/Zsh helper function.

use super::plugin_segments::{
    append_plugin_segment_assignments, append_plugin_segment_file_assignments,
};
use super::segments::{
    append_builtin_segment_assignments, append_delimiter_assignments,
    append_git_language_color_assignments, append_global_assignments, append_hostname_assignments,
    append_prompt_assignments, append_status_assignments, append_username_assignments,
};
use super::shell_assignment::push_line;
use super::shell_colors::ShellColors;
use crate::config::Config;
use crate::formatter::separator::Glyphs;
use crate::shell::Shell;
use crate::template::Palette;
use crate::theme::model::ThemeConfig;
use std::collections::BTreeMap;

/// Emit the provenance header. `theme_name` is raw: it sits in a `#` comment, never expanded.
fn append_header(output: &mut String, shell: Shell, theme_name: &str) {
    push_line(output, format_args!("# GPY Theme: {theme_name}"));
    push_line(
        output,
        format_args!(
            "# Generated by gpy-agent for {}",
            match shell {
                Shell::Fish => "Fish",
                Shell::Zsh => "Zsh",
                Shell::Bash => "Bash",
            }
        ),
    );
    output.push('\n');
}

/// The enabled-segment list; `git`/`language` dropped when disabled in `config`.
fn append_enabled_segments(output: &mut String, shell: Shell, config: &Config) {
    let filtered: Vec<String> = config
        .ui
        .enabled_segments
        .iter()
        .filter(|s| match s.as_str() {
            "git" => config.git.enabled,
            "language" => config.language.enabled,
            _ => true,
        })
        .cloned()
        .collect();
    let segments = filtered.join(" ");

    // Bash needs a space-separated string: `$arr` expands to the first element only.
    match shell {
        Shell::Fish => push_line(output, format_args!("set -g __enabled_segments {segments}")),
        Shell::Zsh => push_line(
            output,
            format_args!("typeset -g -a __enabled_segments=({segments})"),
        ),
        Shell::Bash => push_line(output, format_args!("__enabled_segments=\"{segments}\"")),
    }
}

/// Sorted language marker file names from `marker_file_names()`, for shell pre-filters.
/// Shell-safe; arrays are never exported (Bash can't export arrays).
fn append_lang_marker_files(output: &mut String, shell: Shell) {
    let mut names: Vec<&str> = crate::language::metadata::marker_file_names()
        .iter()
        .copied()
        .collect();
    names.sort_unstable();
    let joined = names.join(" ");

    match shell {
        Shell::Fish => push_line(
            output,
            format_args!("set -g __gpy_lang_marker_files {joined}"),
        ),
        Shell::Zsh => push_line(
            output,
            format_args!("typeset -g -a __gpy_lang_marker_files=({joined})"),
        ),
        Shell::Bash => push_line(output, format_args!("__gpy_lang_marker_files=({joined})")),
    }
}

/// Chevron-relevant segments and their `__color_*_bg` var, in Bash/Zsh case-arm order.
/// `status` is handled separately: its bg depends on the previous exit status.
pub(crate) const SEGMENT_BG_VARS: &[(&str, &str)] = &[
    ("git", "__color_git_clean_bg"),
    ("language", "__color_language_bg"),
    ("directory", "__color_directory_bg"),
    ("duration", "__color_duration_bg"),
    ("clock", "__color_clock_bg"),
    ("hostname", "__color_hostname_bg"),
    ("username", "__color_username_bg"),
];

/// Emit `__gpy_segment_bg` for Bash/Zsh (no-op for Fish).
///
/// `__gpy_segment_bg SEG` prints to stdout; `__gpy_segment_bg SEG VAR` uses
/// `printf -v` to avoid a subshell fork on the hot path.
/// `status` picks ok/fail bg by `__gpy_last_status`.
fn append_segment_bg_function(output: &mut String, shell: Shell) {
    if matches!(shell, Shell::Fish) {
        return;
    }

    output.push('\n');
    push_line(output, format_args!("__gpy_segment_bg() {{"));
    push_line(output, format_args!("    local __gpy_sbg=\"\""));
    push_line(output, format_args!("    case \"$1\" in"));
    for (segment, var) in SEGMENT_BG_VARS {
        push_line(
            output,
            format_args!("        {segment}) __gpy_sbg=\"${{{var}:-}}\" ;;"),
        );
    }
    push_line(output, format_args!("        status)"));
    let (status_var, ok_var, fail_var) = (
        "__gpy_last_status",
        "__color_status_ok_bg",
        "__color_status_fail_bg",
    );
    push_line(
        output,
        format_args!("            if [[ \"${{{status_var}:-0}}\" -eq 0 ]]; then"),
    );
    push_line(
        output,
        format_args!("                __gpy_sbg=\"${{{ok_var}:-green}}\""),
    );
    push_line(output, format_args!("            else"));
    push_line(
        output,
        format_args!("                __gpy_sbg=\"${{{fail_var}:-red}}\""),
    );
    push_line(output, format_args!("            fi"));
    push_line(output, format_args!("            ;;"));
    push_line(output, format_args!("        *) __gpy_sbg=\"\" ;;"));
    push_line(output, format_args!("    esac"));
    push_line(output, format_args!("    if [[ -n \"$2\" ]]; then"));
    push_line(
        output,
        format_args!("        printf -v \"$2\" '%s' \"$__gpy_sbg\""),
    );
    push_line(output, format_args!("    else"));
    push_line(output, format_args!("        printf '%s' \"$__gpy_sbg\""));
    push_line(output, format_args!("    fi"));
    push_line(output, format_args!("}}"));
}

/// Serialize a theme into shell assignments. Call order is the export contract,
/// pinned by snapshots. Every assigned value is escaped once, in
/// [`ShellAssignment::render`](super::shell_assignment::ShellAssignment::render), by
/// [`escape_shell_value`](super::shell_assignment::escape_shell_value); colors are validated
/// upstream and resolved against `palette` (see [`ShellColors`]).
pub(crate) fn theme_to_shell(
    theme: &ThemeConfig,
    theme_name: &str,
    config: &Config,
    shell: Shell,
    palette: &Palette,
    plugin_segment_files: &BTreeMap<String, String>,
) -> String {
    let mut output = String::new();
    let colors = ShellColors { shell, palette };

    append_header(&mut output, shell, theme_name);
    append_global_assignments(&mut output, shell, theme, theme_name, config);
    append_prompt_assignments(&mut output, colors, theme);

    append_builtin_segment_assignments(&mut output, colors, theme);
    append_hostname_assignments(&mut output, colors, theme);
    append_username_assignments(&mut output, colors, theme);
    append_status_assignments(&mut output, colors, theme);
    append_git_language_color_assignments(&mut output, colors, theme);
    append_delimiter_assignments(&mut output, colors, theme, Glyphs::from(&config.ui));

    append_plugin_segment_assignments(&mut output, colors, theme);

    append_plugin_segment_file_assignments(&mut output, shell, plugin_segment_files);
    append_enabled_segments(&mut output, shell, config);
    append_lang_marker_files(&mut output, shell);
    append_segment_bg_function(&mut output, shell);

    output
}
